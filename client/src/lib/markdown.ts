/**
 * Постпроцессинг текста ответа для продуктового вида (отзыв Кости 03.10):
 * 1. Убирает метки источников [... › ...] — они уже в SourcesChip и трейсе
 * 2. Убирает секцию «## Источники» (список меток внизу ответа)
 * 3. Рендерит маркдаун: **жирное**, ## заголовки, - списки, --- разделители
 */

/** Строка-заголовок секции источников: «## Источники», «**Источники:**»,
 * «Источники:» (+ хвостовые запятые/дефисы после вырезания меток).
 * Слово задаём явно: \w в JS не матчит кириллицу, «Источники» ≠ Источник\w*
 * (грабля 031003: заголовок «Источники:» оставался в конце ответа). */
const SOURCES_HEADER_RE =
  /^[ \t]*(?:#{1,3}[ \t]*|\*\*)?[ \t]*Источники?[ \t]*:?[ \t]*(?:\*\*)?[ \t]*[,;·—-]*[ \t]*$/;

/** Убирает исходные метки и секцию источников из текста ответа. */
export function stripSourceLabels(text: string): string {
  let s = text;
  // 1) Секция «Источники» в конце: срезаем от ПОСЛЕДНЕГО заголовка-строки до
  //    разделителя «---»/заголовка ниже либо конца текста (жадно по секции).
  //    Внимание: $ с флагом m матчит конец каждой строки, поэтому секцию
  //    срезаем индексами, а не lookahead.
  let cut = -1;
  for (const m of s.matchAll(new RegExp(SOURCES_HEADER_RE.source, "gm"))) cut = m.index;
  if (cut !== -1) {
    const rest = s.slice(cut);
    const stop = rest.search(/\n[ \t]*(?:-{3,}|#{1,3} )/);
    s = stop === -1 ? s.slice(0, cut) : s.slice(0, cut) + rest.slice(stop);
  }
  // 2) Инлайн-метки [something › something] — вырезаем
  s = s.replace(/\s*\[[^\]\n]*›[^\]\n]*\]/g, "");
  // 3) Заголовок, ставший одиночной строкой ПОСЛЕ вырезания меток
  //    («Источники: [А › Б], [В › Г]» → «Источники:, ,»), — убираем строку
  s = s.replace(new RegExp(SOURCES_HEADER_RE.source + "\\n?", "gm"), "");
  // 4) Орфанные строки-дефисы/буллеты (остатки списка после вырезания меток)
  s = s.replace(/^[ \t]*[-•][ \t]*$\n?/gm, "");
  // 5) Пустые строки-дубли после вырезания
  s = s.replace(/\n{3,}/g, "\n\n");
  // 6) Хвостовые дефисы-разделители без содержимого до них
  s = s.replace(/^---+[ \t]*$\n?/gm, "");
  // 7) Пробелы в конце
  s = s.trimEnd();
  return s;
}

/** Простой маркдаун-рендер для чат-бабблов (без внешних зависимостей). */
export function renderMarkdown(text: string): string {
  // Экранируем HTML (безопасность: модель не должна injecting HTML)
  let s = text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");

  // Заголовки (### → h4, ## → h3, # → h2)
  s = s.replace(/^### (.+)$/gm, "<h4>$1</h4>");
  s = s.replace(/^## (.+)$/gm, "<h3>$1</h3>");
  s = s.replace(/^# (.+)$/gm, "<h2>$1</h2>");

  // Горизонтальная линия
  s = s.replace(/^---+$/gm, "<hr>");

  // Жирный
  s = s.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");

  // Курсив (после жирного, чтобы не перекрыть **)
  s = s.replace(/(?<!\*)\*([^*\n]+)\*(?!\*)/g, "<em>$1</em>");

  // Маркированный список (группируем последовательные - элементы)
  s = s.replace(/(?:^- .+\n?)+/gm, (match) => {
    const items = match
      .trim()
      .split("\n")
      .map((line) => `<li>${line.replace(/^- /, "")}</li>`)
      .join("");
    return `<ul>${items}</ul>`;
  });

  // Параграфы: двойной перенос → новый <p>
  s = s.replace(/\n\n+/g, "</p><p>");
  // Одиночный перенос → <br>
  s = s.replace(/\n/g, "<br>");
  // Оборачиваем
  s = `<p>${s}</p>`;
  // Убираем пустые <p></p>
  s = s.replace(/<p><\/p>/g, "");
  // Убираем <br> перед/после блочных элементов
  s = s.replace(/<br>(<\/?[hu])/g, "$1");
  s = s.replace(/(<\/[hu][0-9]?l?)><br>/g, "$1>");
  // Убираем <p> вокруг блочных элементов
  s = s.replace(/<p>(<h[234]>)/g, "$1");
  s = s.replace(/(<\/h[234]>)<\/p>/g, "$1");
  s = s.replace(/<p>(<ul>)/g, "$1");
  s = s.replace(/(<\/ul>)<\/p>/g, "$1");
  s = s.replace(/<p>(<hr>)<\/p>/g, "$1");

  return s;
}

/** Полный пайплайн: убрать метки → отрендерить маркдаун. */
export function renderReply(text: string): string {
  return renderMarkdown(stripSourceLabels(text));
}
